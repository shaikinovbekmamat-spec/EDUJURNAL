    function kyrgyzEnabled() {
        return document.cookie.split(';').some(function (part) {
            return part.trim() === 'edujournal-language=ky';
        });
    }

    function translateNode(node) {
        if (node.nodeType === Node.TEXT_NODE) {
            const value = node.nodeValue.trim().replace(/\s+/g, ' ');
            if (translations[value]) node.nodeValue = node.nodeValue.replace(/\s+/g, ' ').replace(value, translations[value]);
            return;
        }
        if (node.nodeType !== Node.ELEMENT_NODE || ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(node.tagName)) return;
        ['title', 'placeholder', 'aria-label'].forEach(function (attribute) {
            const value = node.getAttribute(attribute);
            if (value && translations[value]) node.setAttribute(attribute, translations[value]);
        });
        node.childNodes.forEach(translateNode);
    }

    function translate() {
        const kyrgyz = kyrgyzEnabled();
        document.documentElement.lang = kyrgyz ? 'ky' : 'ru';
        if (kyrgyz) {
            translateNode(document.body);
            if (document.title) {
                const title = translations[document.title];
                if (title) document.title = title;
            }
            document.querySelectorAll('.lang-switch a').forEach(function (link) {
                link.classList.toggle('active', (kyrgyz && link.textContent.trim() === 'KG') || (!kyrgyz && link.textContent.trim() === 'RU'));
            });
        }
    }

    document.addEventListener('DOMContentLoaded', translate);
    new MutationObserver(translate).observe(document.documentElement, {childList: true, subtree: true});
