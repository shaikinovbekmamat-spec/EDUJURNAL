create table journal_final_grade (
    id bigint generated by default as identity primary key,
    year_id bigint not null references academic_year(id),
    period_number integer not null check(period_number between 0 and 4),
    school_id bigint not null references schedule_school(id),
    class_id bigint not null,
    subject_id bigint not null,
    student_id bigint not null references users(id),
    teacher_user_id bigint not null references users(id),
    grade_value integer not null check(grade_value between 1 and 5),
    saved_at timestamp with time zone not null default current_timestamp,
    unique(year_id, period_number, subject_id, student_id),
    foreign key(school_id,class_id) references schedule_class(school_id,id),
    foreign key(school_id,subject_id) references schedule_subject(school_id,id)
);
