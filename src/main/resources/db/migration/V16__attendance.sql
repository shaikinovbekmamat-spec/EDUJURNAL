create table attendance (
 lesson_id bigint not null references schedule_lesson(id), student_id bigint not null references users(id),
 status varchar(20) not null check(status in ('PRESENT','ABSENT','LATE')), reason varchar(1000) not null,
 version bigint not null, primary key(lesson_id,student_id)
);
create table attendance_history (
 id bigint generated by default as identity primary key,
 lesson_id bigint not null, student_id bigint not null, actor_id bigint not null references users(id),
 old_status varchar(20), new_status varchar(20) not null, reason varchar(1000) not null,
 correction varchar(1000) not null, changed_at timestamp with time zone not null default current_timestamp,
 foreign key(lesson_id,student_id) references attendance(lesson_id,student_id)
);
create table attendance_notification (
 id bigint generated by default as identity primary key, recipient_id bigint not null references users(id),
 lesson_id bigint not null, student_id bigint not null, read_at timestamp with time zone,
 created_at timestamp with time zone not null default current_timestamp,
 unique(recipient_id,lesson_id,student_id),
 foreign key(lesson_id,student_id) references attendance(lesson_id,student_id)
);
