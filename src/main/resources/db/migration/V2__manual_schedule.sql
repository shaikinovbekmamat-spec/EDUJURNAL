-- Reference tables are deliberately separate from future account/class management.
create table schedule_school (
    id bigint primary key,
    name varchar(150) not null
);
create table schedule_class (
    id bigint primary key,
    school_id bigint not null references schedule_school(id),
    name varchar(100) not null,
    unique (school_id, id)
);
create table schedule_subgroup (
    id bigint primary key,
    school_id bigint not null,
    class_id bigint not null,
    name varchar(100) not null,
    foreign key (school_id, class_id) references schedule_class(school_id, id),
    unique (school_id, class_id, id)
);
create table schedule_membership (
    subgroup_id bigint not null references schedule_subgroup(id),
    student_id bigint not null,
    active_from date not null,
    active_to date,
    primary key (subgroup_id, student_id, active_from),
    check (active_to is null or active_to >= active_from)
);
create table schedule_subject (
    id bigint primary key,
    school_id bigint not null references schedule_school(id),
    name varchar(100) not null,
    unique (school_id, id)
);
create table schedule_teacher (
    id bigint primary key,
    school_id bigint not null references schedule_school(id),
    name varchar(150) not null,
    unique (school_id, id)
);
create table schedule_room (
    id bigint primary key,
    school_id bigint not null references schedule_school(id),
    name varchar(100) not null,
    unique (school_id, id)
);
create table schedule_lesson (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    school_id bigint not null references schedule_school(id),
    class_id bigint not null,
    subgroup_id bigint,
    subject_id bigint not null,
    teacher_id bigint not null,
    room_id bigint not null,
    lesson_date date not null,
    start_time time not null,
    end_time time not null,
    request_token varchar(36) not null unique,
    foreign key (school_id, class_id) references schedule_class(school_id, id),
    foreign key (school_id, class_id, subgroup_id) references schedule_subgroup(school_id, class_id, id),
    foreign key (school_id, subject_id) references schedule_subject(school_id, id),
    foreign key (school_id, teacher_id) references schedule_teacher(school_id, id),
    foreign key (school_id, room_id) references schedule_room(school_id, id),
    check (start_time < end_time)
);
create index schedule_lesson_day on schedule_lesson(school_id, lesson_date);
create index schedule_membership_student on schedule_membership(student_id, subgroup_id);
