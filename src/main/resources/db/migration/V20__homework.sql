-- Домашнее задание
create table homework (
    id bigint generated by default as identity primary key,
    school_id bigint not null references schedule_school(id),
    teacher_id bigint not null references schedule_teacher(id),   -- кто задал
    class_id bigint not null references schedule_class(id),
    subject_id bigint not null references schedule_subject(id),
    lesson_id bigint references schedule_lesson(id),              -- опционально, к какому уроку
    title varchar(200) not null,
    body varchar(10000) not null,
    due_date date not null,                                        -- срок сдачи
    mode varchar(10) not null check (mode in ('NOTEBOOK','ONLINE')), -- тетрадь / сайт
    published_at timestamp with time zone not null default current_timestamp,
    request_token varchar(100) not null unique
);

-- Кому адресовано (весь класс или подгруппа/ученики)
create table homework_audience (
    homework_id bigint not null references homework(id) on delete cascade,
    student_id bigint not null references users(id),
    primary key (homework_id, student_id)
);

-- Ответ ученика (версии: каждая отправка = новая строка)
create table homework_submission (
    id bigint generated by default as identity primary key,
    homework_id bigint not null references homework(id) on delete cascade,
    student_id bigint not null references users(id),
    version int not null,
    text_answer varchar(10000),
    status varchar(20) not null check (status in ('SENT','RETURNED','ACCEPTED')),
    teacher_comment varchar(2000),
    submitted_at timestamp with time zone not null default current_timestamp,
    checked_at timestamp with time zone,
    checked_by bigint references users(id),
    unique (homework_id, student_id, version)
);

-- Файлы ответа
create table homework_file (
    id bigint generated by default as identity primary key,
    submission_id bigint not null references homework_submission(id) on delete cascade,
    name varchar(200) not null,
    content_type varchar(100) not null,
    data bytea not null
);

-- Отметка «бумажная работа сдана» (для mode=NOTEBOOK)
create table homework_paper_mark (
    homework_id bigint not null references homework(id) on delete cascade,
    student_id bigint not null references users(id),
    marked_by bigint not null references users(id),
    marked_at timestamp with time zone not null default current_timestamp,
    primary key (homework_id, student_id)
);

create index homework_school_class_idx on homework(school_id, class_id, due_date);
create index submission_homework_idx on homework_submission(homework_id, student_id);