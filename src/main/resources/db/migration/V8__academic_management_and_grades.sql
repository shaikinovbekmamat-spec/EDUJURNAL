create sequence catalog_id_seq start with 100000;
create table academic_year (
    id bigint generated by default as identity primary key,
    school_id bigint not null references schedule_school(id),
    name varchar(100) not null,
    starts_on date not null,
    ends_on date not null,
    unique(school_id, name),
    check(starts_on < ends_on)
);
create table academic_quarter (
    id bigint generated by default as identity primary key,
    year_id bigint not null references academic_year(id),
    number integer not null check(number between 1 and 4),
    starts_on date not null,
    ends_on date not null,
    unique(year_id, number),
    check(starts_on <= ends_on)
);
create table teaching_assignment (
    school_id bigint not null,
    class_id bigint not null,
    subject_id bigint not null,
    teacher_id bigint not null,
    primary key(school_id, class_id, subject_id, teacher_id),
    foreign key(school_id, class_id) references schedule_class(school_id, id),
    foreign key(school_id, teacher_id, subject_id) references schedule_teacher_subject(school_id, teacher_id, subject_id)
);
insert into teaching_assignment select distinct school_id, class_id, subject_id, teacher_id from schedule_lesson;
create table parent_student (
    parent_id bigint not null references users(id),
    student_id bigint not null references users(id),
    confirmed_by bigint not null references users(id),
    confirmed_at timestamp with time zone not null default current_timestamp,
    primary key(parent_id, student_id),
    check(parent_id <> student_id)
);
create table journal_grade (
    id bigint generated by default as identity primary key,
    lesson_id bigint not null references schedule_lesson(id),
    student_id bigint not null references users(id),
    teacher_user_id bigint not null references users(id),
    quarter_id bigint not null references academic_quarter(id),
    grade_value integer not null check(grade_value between 1 and 5),
    saved_at timestamp with time zone not null default current_timestamp,
    unique(lesson_id, student_id)
);
create index grade_student on journal_grade(student_id, quarter_id);
