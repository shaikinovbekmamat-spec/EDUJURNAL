[CmdletBinding()]
param([string]$OutputDirectory = (Join-Path $PSScriptRoot '../target/backup-verification/backups'))
. (Join-Path $PSScriptRoot 'backup-common.ps1')
$suffix=[Guid]::NewGuid().ToString('N').Substring(0,12)
$source='edujournal_verify_' + $suffix
$restored='edujournal_restore_' + $suffix
Invoke-Pg 'createdb' @('--no-password','--maintenance-db','postgres','--template=template0',$source)
# Synthetic data only. Neither production credentials nor production records are required.
$sql=@'
create table users(id bigint generated by default as identity primary key, login text, role text, password text);
create table parent_student(parent_id bigint references users,student_id bigint references users);
create table academic_year(id bigint primary key,archived boolean,archived_by bigint references users);
create table journal_grade(id bigint generated by default as identity primary key,student_id bigint references users,grade_value int);
create table homework_file(id bigint primary key,data bytea);
create table message_attachment(id bigint primary key,data bytea);
insert into users(login,role,password) values('student','STUDENT','synthetic-hash'),('parent','PARENT','synthetic-hash'),('director','DIRECTOR','synthetic-hash');
insert into parent_student values(2,1);
insert into academic_year values(1,true,3);
insert into journal_grade(student_id,grade_value) values(1,5);
insert into homework_file values(1,decode('00010a0d7f80ff','hex'));
insert into message_attachment values(1,decode('255044460001ff','hex'));
create function prevent_grade_edit() returns trigger language plpgsql as $$begin raise exception 'immutable'; end$$;
create trigger immutable_grade before update on journal_grade for each row execute function prevent_grade_edit();
'@
Invoke-Pg 'psql' @('--no-password','--no-psqlrc','--set','ON_ERROR_STOP=1','--dbname',$source,'--command',$sql) | Out-Null
& (Join-Path $PSScriptRoot 'backup.ps1') -Database $source -OutputDirectory $OutputDirectory
$manifest=Get-ChildItem -LiteralPath $OutputDirectory -Filter 'edujournal-*.json' | Where-Object {
    (Get-Content -LiteralPath $_.FullName -Raw | ConvertFrom-Json).database -eq $source
} | Select-Object -First 1
& (Join-Path $PSScriptRoot 'restore.ps1') -ManifestPath $manifest.FullName -TargetDatabase $restored
$query=@'
select 'users',string_agg(login||':'||role||':'||password,',' order by id) from users
union all select 'links',string_agg(parent_id||':'||student_id,',' order by parent_id) from parent_student
union all select 'archive',string_agg(id||':'||archived||':'||archived_by,',' order by id) from academic_year
union all select 'grades',string_agg(id||':'||student_id||':'||grade_value,',' order by id) from journal_grade
union all select 'homework',string_agg(encode(data,'hex'),',' order by id) from homework_file
union all select 'attachments',string_agg(encode(data,'hex'),',' order by id) from message_attachment
union all select 'sequence',nextval(pg_get_serial_sequence('users','id'))::text
union all select 'trigger',count(*)::text from pg_trigger where tgname='immutable_grade'
order by 1;
'@
$before=Invoke-Pg 'psql' @('--no-password','--no-psqlrc','--tuples-only','--no-align','--dbname',$source,'--command',$query)
$after=Invoke-Pg 'psql' @('--no-password','--no-psqlrc','--tuples-only','--no-align','--dbname',$restored,'--command',$query)
if (Compare-Object $before $after) { throw 'Restored data differs from the source.' }
$rejected=$false
try { & (Join-Path $PSScriptRoot 'restore.ps1') -ManifestPath $manifest.FullName -TargetDatabase $restored } catch { $rejected=$_.Exception.Message -like '*already exists*' }
if (!$rejected) { throw 'Existing database protection failed.' }
$bad=Get-Content -LiteralPath $manifest.FullName -Raw | ConvertFrom-Json
$bad.sha256='0' * 64
$badPath=Join-Path $OutputDirectory 'invalid-checksum.json'
$bad | ConvertTo-Json | Set-Content -LiteralPath $badPath -Encoding UTF8
$rejected=$false
try { & (Join-Path $PSScriptRoot 'restore.ps1') -ManifestPath $badPath -TargetDatabase ($restored+'_bad') } catch { $rejected=$_.Exception.Message -like '*checksum mismatch*' }
if (!$rejected) { throw 'Checksum protection failed.' }
Write-Output "PASS: records, roles, parent links, archive, binary attachments, sequences and trigger restored. Existing database and corrupt backup rejected. Test databases retained: $source, $restored"
